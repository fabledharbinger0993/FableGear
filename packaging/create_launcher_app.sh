#!/bin/bash
# FableGear — create the FableGear.app launcher
#
# Shared by setup.sh (Terminal install) and installer_wizard.py (GUI install) so the
# two can't drift apart.
#
# Usage: create_launcher_app.sh <path-to-FableGear-folder> [destination-folder]
#
# With no destination the app goes to ~/Applications (the Terminal/source-install behaviour).
# The GUI installer passes /Applications, or ~/Applications when /Applications isn't writable.
# Safe to re-run. Always exits 0: a missing launcher is an inconvenience, not an install
# failure, and the output already tells the user to run launch.sh directly.
#
# The app is a shell script, not an AppleScript applet: Finder surfaces generic
# "/bin/bash" alerts when an osacompile do-shell-script wrapper fails, and a plain
# script app needs no code signature. It carries no code of its own -- it hands off
# to <FableGear folder>/launch.sh, so updating the folder updates the app.

SCRIPT_DIR="${1:?usage: create_launcher_app.sh <FableGear folder> [destination folder]}"
DEST_DIR="${2:-$HOME/Applications}"

ok()   { echo "  ✓  $1"; }
info() { echo "     $1"; }

BUNDLE_ID="com.fabledharbinger.fablegear"
APP_DEST="$DEST_DIR/FableGear.app"

if [ ! -f "$SCRIPT_DIR/launch.sh" ]; then
  info "No launch.sh in $SCRIPT_DIR — not creating a launcher."
  exit 0
fi

mkdir -p "$DEST_DIR" 2>/dev/null

# Replace only a FableGear launcher of ours: never clobber some other app that happens
# to be called FableGear.app.
if [ -d "$APP_DEST" ]; then
  existing_id="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIdentifier' "$APP_DEST/Contents/Info.plist" 2>/dev/null)"
  # Only our exact bundle id counts as ours (the old release's launcher used it too). Anything else,
  # including an AppleScript applet or a bundle with no identifier, is left alone rather than deleted.
  if [ "$existing_id" != "$BUNDLE_ID" ]; then
    info "$APP_DEST is not a FableGear launcher (id: ${existing_id:-none}) — leaving it alone."
    exit 0
  fi
  rm -rf "$APP_DEST"
fi

mkdir -p "$APP_DEST/Contents/MacOS" "$APP_DEST/Contents/Resources" 2>/dev/null

# Shell-quote the folder for embedding in the generated script.
quoted_dir="$(printf '%q' "$SCRIPT_DIR")"

cat > "$APP_DEST/Contents/MacOS/FableGear" <<LAUNCHER
#!/bin/bash
# Generated by FableGear's installer. Hands off to the installed copy.
INSTALL_DIR=$quoted_dir

# Launch Services can run script apps translated (x86_64) on Apple Silicon, which
# makes \`uname -m\` lie to launch.sh's arch check. Re-exec natively first.
if [ "\$(/usr/sbin/sysctl -in sysctl.proc_translated 2>/dev/null)" = "1" ]; then
  exec /usr/bin/arch -arm64 /bin/bash "\$0" "\$@"
fi

if [ ! -f "\$INSTALL_DIR/launch.sh" ]; then
  /usr/bin/osascript -e 'display dialog "FableGear cannot find its files. Run the FableGear installer again to repair the installation." buttons {"OK"} default button "OK" with icon caution with title "FableGear"' >/dev/null 2>&1
  exit 1
fi

# Detach so the Dock icon settles; launch.sh owns the rest.
nohup /bin/bash "\$INSTALL_DIR/launch.sh" >/dev/null 2>&1 &
LAUNCHER
chmod +x "$APP_DEST/Contents/MacOS/FableGear" 2>/dev/null

cat > "$APP_DEST/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleExecutable</key><string>FableGear</string>
  <key>CFBundleIconFile</key><string>applet</string>
  <key>CFBundleIdentifier</key><string>$BUNDLE_ID</string>
  <key>CFBundleName</key><string>FableGear</string>
  <key>CFBundleDisplayName</key><string>FableGear</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$(cat "$SCRIPT_DIR/VERSION" 2>/dev/null | sed 's/^v//;s/[^0-9A-Za-z.+-]//g')</string>
  <key>LSMinimumSystemVersion</key><string>12.0</string>
  <key>NSHighResolutionCapable</key><true/>
</dict>
</plist>
PLIST

if [ -x "$APP_DEST/Contents/MacOS/FableGear" ] && [ -f "$APP_DEST/Contents/Info.plist" ]; then
  ok "FableGear.app created at $APP_DEST"

  # ── Apply icon (sips + iconutil) ────────────────────────────────────────
  ICON_SRC="$SCRIPT_DIR/static/fablegear.png"
  if [ -f "$ICON_SRC" ]; then
    ICONSET="$(mktemp -d)/fg.iconset"
    mkdir -p "$ICONSET"
    for size in 16 32 64 128 256 512; do
      sips -z "$size" "$size" "$ICON_SRC" \
        --out "$ICONSET/icon_${size}x${size}.png" >/dev/null 2>&1
      double=$((size * 2))
      sips -z "$double" "$double" "$ICON_SRC" \
        --out "$ICONSET/icon_${size}x${size}@2x.png" >/dev/null 2>&1
    done
    iconutil -c icns "$ICONSET" \
      -o "$APP_DEST/Contents/Resources/applet.icns" 2>/dev/null && \
      ok "Icon applied" || info "Icon apply skipped (iconutil unavailable)"
    rm -rf "$(dirname "$ICONSET")"
    # Touch the bundle so LaunchServices notices the new icon.
    touch "$APP_DEST"
  fi

  info "Drag it to your Dock for one-click access."
  info "Or double-click it from $DEST_DIR."
else
  info "Could not create FableGear.app — run launch.sh directly from Terminal."
fi

exit 0
