"""Write fablegear/iron/key_net_weights.py from a model exported by key_lab_scale.py --export.

The key model of docs/IRON_RESEARCH.md SS31 is a small tonic-equivariant net (a few thousand numbers
per seed, several seeds averaged). Its weights ship as a generated Python module -- float32 arrays,
base64-encoded -- so they travel with the code in every packaging path, with no data file to lose.

    venv/bin/python dev/scripts/experiments/key_lab_export_weights.py ~/FableGearTestbed/keylab/scale_model.json
"""

from __future__ import annotations

import base64
import json
import sys
from pathlib import Path

import numpy as np

OUT = Path(__file__).resolve().parents[3] / "fablegear" / "iron" / "key_net_weights.py"


def _b64(a) -> str:
    return base64.b64encode(np.asarray(a, dtype="<f4").tobytes()).decode("ascii")


def main(src: Path) -> None:
    m = json.loads(src.read_text())
    cfg = m["cfg"]
    if cfg["family"] != "net" or cfg["views"] != "whole":
        raise SystemExit(f"only whole-view nets are supported here, got {cfg}")
    seeds = []
    for model in m["models"]:
        _, W, A, c, v, b = model
        seeds.append((np.asarray(W), np.asarray(A), np.asarray(c), np.asarray(v), np.asarray(b)))
    hidden, dim = seeds[0][1].shape
    lines = [
        '"""Key model weights (docs/IRON_RESEARCH.md SS31). GENERATED by',
        "dev/scripts/experiments/key_lab_export_weights.py from key_lab_scale.py's export -- do not edit.",
        "",
        f"A tonic-equivariant net fitted on {m['n_train']:,} Rekordbox-analysed tracks of the owner's library,",
        f"cfg {cfg}. Each seed: W (2, {dim}), A ({hidden}, {dim}), c ({hidden},), v (2, {hidden}), b (2,),",
        'float32 little-endian, base64. iron.key averages the seeds\' logits."""',
        "",
        f"HIDDEN = {hidden}",
        f"DIM = {dim}",
        "SEEDS = (",
    ]
    for W, A, c, v, b in seeds:
        lines.append("    (")
        for name, arr in (("W", W), ("A", A), ("c", c), ("v", v), ("b", b)):
            enc = _b64(arr)
            chunks = [enc[i:i + 96] for i in range(0, len(enc), 96)]
            lines.append(f"        # {name}")
            lines.append("        (" + "\n         ".join(f'"{ch}"' for ch in chunks) + "),")
        lines.append("    ),")
    lines.append(")")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size:,} bytes, {len(seeds)} seeds, H={hidden})")


if __name__ == "__main__":
    main(Path(sys.argv[1]))
