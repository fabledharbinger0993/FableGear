"""Regenerate fablegear/chop_shop/devicesql_canned.py from the committed Rekordbox capture.

The DeviceSQL writer needs a handful of rows that hold no library data: the eight track colours, the
27 browse columns, the browse-menu layout (table 0x11), table 0x12, and exportExt.pdb's default
My Tag set. They are copied verbatim from tests/fixtures/rekordbox_21track_export (the stick a
CDJ-3000 on firmware 3.2x loaded), in row order, so the writer reproduces what a real deck accepted.
Colours, columns and table 0x12 are byte-identical in the untouched ground-truth export too.

    venv/bin/python dev/scripts/devicesql_canned_extract.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "fablegear"))

from chop_shop import devicesql_reader as R  # noqa: E402

CAPTURE = REPO / "dev/tests/fixtures/rekordbox_21track_export/PIONEER/rekordbox"
OUT = REPO / "fablegear/chop_shop/devicesql_canned.py"

# (constant name, file, number of tables in that file, table type)
WANTED = [
    ("EXPORT_COLORS", "export.pdb", 20, 0x06),
    ("EXPORT_COLUMNS", "export.pdb", 20, 0x10),
    ("EXPORT_MENU_0x11", "export.pdb", 20, 0x11),
    ("EXPORT_TABLE_0x12", "export.pdb", 20, 0x12),
    ("EXT_MY_TAGS", "exportExt.pdb", 9, 0x03),
    ("EXT_TABLE_0x07", "exportExt.pdb", 9, 0x07),
]


def present_rows(path: Path, num_tables: int, table_type: int) -> list[bytes]:
    out: list[bytes] = []
    with open(path, "rb") as fh:
        pointers = R._read_table_pointers(fh, num_tables)
        ptr = next(p for p in pointers if p.table_type == table_type)
        for page in R._walk_table_pages(fh, 4096, ptr.first_page, ptr.last_page):
            header = R._parse_page_header(page)
            slots = R._row_slots(page, 4096, header.num_row_offsets)
            offsets = sorted({o for o, _ in slots})
            used = int.from_bytes(page[0x1E:0x20], "little")
            for ofs, present in slots:
                if present:
                    end = min([o for o in offsets if o > ofs], default=used)
                    out.append(page[0x28 + ofs:0x28 + end])
    return out


def main() -> None:
    lines = [
        '"""Fixed DeviceSQL rows copied from a Rekordbox export a CDJ-3000 (firmware 3.2x) loaded.',
        "",
        "GENERATED by dev/scripts/devicesql_canned_extract.py from",
        "dev/tests/fixtures/rekordbox_21track_export/ -- do not edit by hand. None of these rows holds",
        "library data: track colours, browse columns, the browse-menu layout, table 0x12, and the",
        'default My Tag set of exportExt.pdb. Each tuple is the present rows of one table, in row order."""',
        "",
    ]
    for name, file, n_tables, table_type in WANTED:
        rows = present_rows(CAPTURE / file, n_tables, table_type)
        lines.append(f"{name}: tuple[bytes, ...] = (")
        lines += [f'    bytes.fromhex("{r.hex()}"),' for r in rows]
        lines.append(")")
        lines.append("")
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
